//! Typed action → fixed argv, and the sudoers rules that permit exactly those
//! argvs. The argv builder itself lives in `sbc_core::plan` so the browser
//! playground runs the same code as this gate.
//!
//! The agent logs in as an unprivileged user (`sbc-agent`). Privileged
//! actions go through `sudo -n` with sudoers rules that list the exact
//! commands for exactly the enrolled services (see `render_sudoers`), so even
//! the gate itself cannot do more than the host operator allowed.

use crate::config::Backend;
use sbc_core::action::{ActionKind, ParsedCommand};
use sbc_core::plan::ServiceManager;
pub use sbc_core::plan::{log_bucket, JOURNALCTL, LOG_BUCKETS, SUDO, SUPERVISORCTL, SYSTEMCTL};

fn manager(backend: Backend) -> ServiceManager {
    match backend {
        Backend::Supervisor => ServiceManager::Supervisor,
        Backend::Systemd | Backend::DryRun => ServiceManager::Systemd,
    }
}

/// The exact argv the gate will execute for a parsed command.
pub fn argv(backend: Backend, cmd: &ParsedCommand) -> Vec<String> {
    sbc_core::plan::argv(manager(backend), cmd)
}

fn sudoers_escape(arg: &str) -> String {
    // sudoers treats , : = \ specially inside command arguments
    let mut o = String::new();
    for c in arg.chars() {
        if matches!(c, ',' | ':' | '=' | '\\') {
            o.push('\\');
        }
        o.push(c);
    }
    o
}

/// `/etc/sudoers.d/sbc-gate`: exact command lines, nothing else.
pub fn render_sudoers(backend: Backend, user: &str, services: &[String]) -> String {
    use sbc_core::action::{Action, ActionParams};
    let mut cmds: Vec<String> = Vec::new();
    for svc in services {
        for kind in ActionKind::ALL {
            let buckets: Vec<u32> = if *kind == ActionKind::LogsRead { LOG_BUCKETS.to_vec() } else { vec![100] };
            for b in buckets {
                let pc = ParsedCommand {
                    action: Action { kind: *kind, target: svc.clone() },
                    params: ActionParams { log_lines: b },
                    via_sudo: true,
                };
                let a = argv(backend, &pc);
                // drop the leading `sudo -n`
                cmds.push(a[2..].iter().map(|x| sudoers_escape(x)).collect::<Vec<_>>().join(" "));
            }
        }
    }
    cmds.dedup();
    let mut out = String::new();
    out.push_str("# /etc/sudoers.d/sbc-gate — generated by `sbc-gate sudoers`.\n");
    out.push_str("# Exact commands for exactly the services this host exposes. No wildcards.\n");
    out.push_str(&format!("Defaults:{} !requiretty, env_reset, !setenv, secure_path=\"/usr/sbin:/usr/bin:/sbin:/bin\"\n", user));
    if cmds.is_empty() {
        out.push_str("# (no services enrolled)\n");
        return out;
    }
    out.push_str(&format!("{} ALL=(root) NOPASSWD: \\\n    ", user));
    out.push_str(&cmds.join(", \\\n    "));
    out.push('\n');
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use sbc_core::action::parse_command;

    #[test]
    fn argv_never_contains_agent_text() {
        let p = parse_command("sudo systemctl restart checkout-api").unwrap();
        assert_eq!(argv(Backend::Systemd, &p), vec![SUDO, "-n", SYSTEMCTL, "restart", "checkout-api"]);
        assert_eq!(argv(Backend::DryRun, &p), vec![SUDO, "-n", SYSTEMCTL, "restart", "checkout-api"]);
        assert_eq!(argv(Backend::Supervisor, &p), vec![SUDO, "-n", SUPERVISORCTL, "restart", "checkout-api"]);
        let l = parse_command("journalctl -u checkout-api -n 70").unwrap();
        assert_eq!(argv(Backend::Systemd, &l), vec![SUDO, "-n", JOURNALCTL, "-u", "checkout-api", "-n", "100", "--no-pager"]);
    }

    #[test]
    fn sudoers_lists_exact_commands() {
        let s = render_sudoers(Backend::Systemd, "sbc-agent", &["checkout-api".into(), "getty@tty1:x".into()]);
        assert!(s.contains("/usr/bin/systemctl restart checkout-api"));
        assert!(s.contains("/usr/bin/journalctl -u checkout-api -n 1000 --no-pager"));
        assert!(s.contains("getty@tty1\\:x"), "colons are escaped for sudoers: {s}");
        assert!(!s.contains('*'), "no wildcards");
        assert!(!s.contains("ALL=(ALL)"));
    }
}
